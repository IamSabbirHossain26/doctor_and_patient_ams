<section class="section">
    <h2 class="section-title">About DPAMS</h2>
    <p>
        The <strong>Doctor &amp; Patient Appointment Management System</strong> is a web-based hospital
        appointment system built with <strong>PHP, CodeIgniter 4 and MySQL</strong> following the
        MVC architecture. It manages Doctors, Patients, Appointments (with bill &amp; test summary)
        and Reports across four primary tables.
    </p>

    <h3>Roles</h3>
    <ul class="list">
        <li><strong>Doctor</strong> — profile with description, skills &amp; services; views appointments, patient info and reports.</li>
        <li><strong>Patient</strong> — registers, books appointments, views bills and collects test reports.</li>
        <li><strong>Staff Nurse</strong> — manages patient info, assists appointments and manages reports.</li>
        <li><strong>Manager / Representative</strong> — manages doctors, patients, staff, appointments, bills and reports.</li>
    </ul>

    <h3>Modules</h3>
    <ul class="list">
        <li>Doctor Management</li>
        <li>Patient Management</li>
        <li>Staff / Role Management</li>
        <li>Appointment Management (with slot-conflict validation)</li>
        <li>Bill Management</li>
        <li>Test &amp; Report Management (with protected file uploads)</li>
    </ul>
</section>
